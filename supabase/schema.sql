-- Darshan AI database schema for the current backend implementation.
-- Run in Supabase SQL Editor using a trusted project owner account.

create extension if not exists pgcrypto;

-- User-scoped RAG chunks. Embeddings are JSONB because the current backend
-- computes similarity in Python rather than using pgvector operators.
create table if not exists public.darshan_ai_chunks (
  id bigint generated by default as identity primary key,
  user_id text not null,
  source text not null,
  chunk_index integer not null,
  content text not null,
  embedding jsonb not null default '[]'::jsonb,
  char_start integer not null default 0,
  char_end integer not null default 0,
  created_at timestamptz not null default now(),
  unique (user_id, source, chunk_index)
);

create index if not exists darshan_ai_chunks_user_id_idx
  on public.darshan_ai_chunks (user_id);

alter table public.darshan_ai_chunks enable row level security;
-- No browser-facing policies are added: the service-role backend accesses this table.

-- Human approval records are created and consumed only by the authenticated backend.
create table if not exists public.darshan_ai_action_approvals (
  action_id uuid primary key default gen_random_uuid(),
  user_id text not null,
  action_type text not null,
  parameters jsonb not null default '{}'::jsonb,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'consumed', 'expired')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '15 minutes'),
  approved_at timestamptz,
  consumed_at timestamptz
);

create index if not exists darshan_ai_action_approvals_owner_status_idx
  on public.darshan_ai_action_approvals (user_id, status, expires_at);

alter table public.darshan_ai_action_approvals enable row level security;
-- No client policies: approval decisions must pass through the authenticated API.
